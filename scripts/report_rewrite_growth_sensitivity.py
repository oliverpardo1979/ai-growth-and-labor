"""Report analytical growth sensitivity without solving transition paths.

Reads the stored illustrative scenario and checks the direct return formula
against its logarithmic form and the regime threshold. No simulation inputs
or existing results are changed.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    scenario = json.loads((ROOT / 'numerical_rewrite/rsi_chi_7_5/scenario.json').read_text())
    p = scenario['parameters']
    alpha, omega = p['alpha'], p['omega_x']
    rho, delta, gamma = p['discount'], p['depreciation'], p['labor_productivity_growth']
    theta = (1 - alpha) / alpha
    bounds = [1000.0, scenario['frontier'], 1500.0, 2000.0]
    sigmas = [1.45, 1.50, 1.55, 1.60, 2.00]
    rows = []
    for sigma in sigmas:
        threshold = ((rho + gamma + delta) / alpha) ** (1 / theta) / (
            (1 - alpha) ** 2 * omega ** (sigma / (sigma - 1)))
        cells = []
        for bound in bounds:
            gross_return = alpha * ((1 - alpha) ** 2 * bound * omega ** (
                sigma / (sigma - 1))) ** theta
            log_return = math.log(alpha) + theta * (
                2 * math.log1p(-alpha) + math.log(bound)
                + sigma / (sigma - 1) * math.log(omega))
            assert math.isclose(gross_return, math.exp(log_return), rel_tol=1e-12)
            ai_dominated = bound > threshold
            assert ai_dominated == (gross_return - delta - rho > gamma)
            growth = gross_return - delta - rho if ai_dominated else gamma
            cells.append(dict(bound=bound, growth=growth,
                              regime='AI-dominated' if ai_dominated else 'labor-bottleneck'))
        rows.append(dict(sigma=sigma, threshold=threshold, cells=cells))
    # The stored design deliberately places sigma=1.5 ten percent above its threshold.
    assert math.isclose(bounds[1] / rows[1]['threshold'], 1.1, rel_tol=1e-12)
    return dict(source='numerical_rewrite/rsi_chi_7_5/scenario.json',
                parameters=p, bounds=bounds, rows=rows,
                units='100 times the continuous-time annual growth rate',
                scope='Analytical regime limits, not transition solutions or global existence claims')


def render(report):
    lines = [r'% Generated by scripts/report_rewrite_growth_sensitivity.py.',
             r'\begin{table}[htbp]', r'\centering',
             r'\caption{Sensitivity of long-run output-per-worker growth}',
             r'\label{tab:rewrite-growth-sensitivity}',
             r'\small\setstretch{1.0}', r'\begin{tabular}{lrrrr}',
             r'\toprule', r'& \multicolumn{4}{c}{AI-efficiency upper bound $\overline B$}\\',
             r'$\sigma$ & 1,000 & 1,361 & 1,500 & 2,000\\', r'\midrule']
    for row in report['rows']:
        values = [f"{100 * c['growth']:,.1f}" for c in row['cells']]
        lines.append(f"{row['sigma']:.2f} & " + ' & '.join(values) + r'\\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\par\vspace{4pt}',
              r'\parbox{0.95\textwidth}{\footnotesize\emph{Notes:} Entries are annual continuous-time growth rates in percent. I use $\gamma$ in the labor-bottleneck regime and $\mathcal R(\overline B)-\rho$ in the AI-dominated regime, as characterized in Proposition~\ref{prop:rewrite-equilibrium-regimes}. All other parameters retain the values in Table~\ref{tab:rewrite-rsi-parameters}, including the CES weights. The column labeled 1,361 uses the unrounded simulation bound, $1.10\mathcal B(1.50)$. These are analytical long-run rates, not additional simulated transitions.}',
              r'\end{table}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    report = build()
    output = ROOT / 'numerical_rewrite/growth_sensitivity'
    output.mkdir(parents=True, exist_ok=True)
    (output / 'analytical_rates.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    (ROOT / 'sections_rewrite/growth_sensitivity.tex').write_text(render(report), encoding='utf-8')
    print(json.dumps(report, indent=2))
